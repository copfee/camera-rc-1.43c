// Deterministic conversion of the selected brand and supplied model assets for the embedded UI.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { Resvg } from '@resvg/resvg-js';
import { PNG } from 'pngjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = readFileSync(resolve(root, 'components/ui/assets/fujifilm_glow_imagegen_reference.png'));
const checksum = createHash('sha256').update(source).digest('hex');
if (checksum !== 'da1003c5598e32632f04a2cedbce9ac9fb4dc68ba61dfc91c7cecff707297f61') {
  throw new Error('ImageGen logo source SHA-256 mismatch');
}
// Crop transparent margins and resample to the existing 196x46 UI footprint.
const width = 196, height = 46;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="196" height="46" viewBox="100 145 1960 460"><image width="2167" height="726" href="data:image/png;base64,${source.toString('base64')}"/></svg>`;
const png = PNG.sync.read(new Resvg(svg).render().asPng());
writeFileSync(resolve(root, 'components/ui/assets/fujifilm_outline.png'), PNG.sync.write(png));
function writeResource(png, name, checksum) {
  const {width, height} = png;
  const bytes = [];
  for (let i = 0; i < png.data.length; i += 4) bytes.push(png.data[i + 2], png.data[i + 1], png.data[i], png.data[i + 3]);
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) rows.push('    ' + bytes.slice(i, i + 16).map(n => `0x${n.toString(16).padStart(2, '0')}`).join(', ') + ',');
  writeFileSync(resolve(root, `components/ui/src/${name}.c`), `// Generated by tools/assets/generate.mjs. Do not edit.\n// Source SHA-256: ${checksum}\n#include "lvgl.h"\n\nstatic const uint8_t pixels[] = {\n${rows.join('\n')}\n};\n\nconst lv_image_dsc_t rc_${name} = {\n    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,\n                .w = ${width}, .h = ${height}, .stride = ${width * 4} },\n    .data_size = sizeof(pixels),\n    .data = pixels,\n};\n`);
}
writeResource(png, 'fujifilm_logo', checksum);
console.log(`Logo ${width}x${height}; source SHA-256: ${checksum}`);

// The supplied WebP is decoded losslessly to PNG once with sharp 0.35.5.
// Both originals are checked in, so generation needs only the pinned PNG/SVG tools.
const modelWebp = readFileSync(resolve(root, 'components/ui/assets/xe5_logo_source.webp'));
const modelSource = readFileSync(resolve(root, 'components/ui/assets/xe5_logo_source.png'));
const modelChecksum = createHash('sha256').update(modelSource).digest('hex');
if (createHash('sha256').update(modelWebp).digest('hex') !== '6ebaa8f2ffa8e796c71f999eb778f6457bbaeae0960c958bfed04dd1e088945a' ||
    modelChecksum !== '829b85754267e291d3abbd566ea88b6d20f76e82f995daa201a87520c8673e93') {
  throw new Error('X-E5 logo source SHA-256 mismatch');
}
const modelSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="100" height="18" viewBox="0 0 249 44" preserveAspectRatio="xMidYMid meet"><image width="249" height="44" href="data:image/png;base64,${modelSource.toString('base64')}"/></svg>`;
const model = PNG.sync.read(new Resvg(modelSvg).render().asPng());
writeFileSync(resolve(root, 'components/ui/assets/xe5_logo.png'), PNG.sync.write(model));
writeResource(model, 'xe5_logo', modelChecksum);
console.log(`X-E5 ${model.width}x${model.height}; source SHA-256: ${modelChecksum}`);

// Matching ImageGen shutter states share one crop and output size.
for (const [state, expected] of [
  ['idle', '7a541d19935610ea7d02a3f0a74b2103d8f7ddf45bed94e7000d3f39d49dfddd'],
  ['pressed', '1f3e29cda31718950a3e3289a4405abdf6468ad3fe1fac4cfa105f15116ffaa2'],
]) {
  const source = readFileSync(resolve(root, `components/ui/assets/shutter_${state}_source.png`));
  const checksum = createHash('sha256').update(source).digest('hex');
  if (checksum !== expected) throw new Error(`Shutter ${state} source SHA-256 mismatch`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="260" height="260" viewBox="60 30 1150 1150"><image width="1271" height="1238" href="data:image/png;base64,${source.toString('base64')}"/></svg>`;
  const image = PNG.sync.read(new Resvg(svg).render().asPng());
  writeResource(image, `shutter_${state}`, checksum);
  console.log(`Shutter ${state} 260x260; source SHA-256: ${checksum}`);
  const fullSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="466" height="466" viewBox="60 30 1150 1150"><image width="1271" height="1238" href="data:image/png;base64,${source.toString('base64')}"/></svg>`;
  writeResource(PNG.sync.read(new Resvg(fullSvg).render().asPng()), `shutter_${state}_full`, checksum);
}
